/**
 * Copies every product photo still loaded from Mallcom's Shopify CDN into
 * public/products/gallery/<product key>/<n>.webp and writes
 * src/data/localImages.generated.js, recording how many copies each product has.
 *
 * Why: ~1,500 gallery and swatch photos were hotlinked from cdn.shopify.com, so
 * the site depended on Mallcom's store keeping every file at the same address.
 *
 * Each photo is normalised the same way: EXIF-rotated, scaled to fit within
 * 1000x1000 (never enlarged), transparency flattened onto white, saved as WebP.
 *
 * File n of a product is the n-th distinct URL in imgs, then variant images
 * (width hint stripped). products.js rebuilds that same list, so the manifest
 * only records how many copies each product has.
 *
 * Usage: node scripts/localize-images.mjs     (resumable; existing files are skipped)
 * Only products currently listed on the site are processed.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outRoot = path.join(root, 'public/products/gallery');
const manifestFile = path.join(root, 'src/data/localImages.generated.js');

// Which products are listed comes from products.js; their photo URLs must come from
// the raw storefront snapshot, because products.js already swaps in local copies.
const { allProducts: listed } = await import(pathToFileURL(path.join(root, 'src/data/products.js')).href);
const { catalog: storefront } = await import(pathToFileURL(path.join(root, 'src/data/catalog.generated.js')).href);
const rawByKey = new Map(Object.values(storefront).flat().map((p) => [p.slug, p]));
const allProducts = listed.map((p) => rawByKey.get(p.key)).filter(Boolean).map((p) => ({ ...p, key: p.slug }));

/** Shopify URLs differ only by a &width= hint; key on the URL without it. */
export const baseUrl = (u) => u.replace(/[?&]width=\d+/, '').replace(/\?$/, '');

const jobs = [];
for (const p of allProducts) {
  const urls = [...(p.imgs || []), ...(p.variants || []).map((v) => v.img).filter(Boolean)]
    .filter((u) => /^https?:\/\//.test(u))
    .map(baseUrl);
  [...new Set(urls)].forEach((url, i) => {
    jobs.push({ url, key: p.key, n: i + 1, file: path.join(outRoot, p.key, `${i + 1}.webp`) });
  });
}

const counts = {};
const failedKeys = new Set();
let done = 0, skipped = 0;
const failed = [];
const worker = async () => {
  for (let job = jobs.shift(); job; job = jobs.shift()) {
    counts[job.key] = Math.max(counts[job.key] || 0, job.n);
    if (fs.existsSync(job.file)) { skipped++; continue; }
    let ok = false;
    for (let attempt = 1; attempt <= 3 && !ok; attempt++) {
      try {
        const res = await fetch(`${job.url}${job.url.includes('?') ? '&' : '?'}width=1200`);
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        const buf = Buffer.from(await res.arrayBuffer());
        fs.mkdirSync(path.dirname(job.file), { recursive: true });
        await sharp(buf)
          .rotate()
          .resize({ width: 1000, height: 1000, fit: 'inside', withoutEnlargement: true })
          .flatten({ background: '#ffffff' })
          .webp({ quality: 80 })
          .toFile(job.file);
        ok = true;
        done++;
      } catch (e) {
        if (attempt === 3) { failed.push(`${job.url} (${e.message})`); failedKeys.add(job.key); }
        else await new Promise((r) => setTimeout(r, 1500 * attempt));
      }
    }
    if ((done + skipped) % 100 === 0) console.log(`${done + skipped} processed`);
  }
};
const total = jobs.length;
await Promise.all(Array.from({ length: 8 }, worker));

// A product with any failed copy keeps its CDN URLs rather than pointing at a missing file.
const sorted = Object.fromEntries(Object.entries(counts).filter(([k]) => !failedKeys.has(k)).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(manifestFile, `// AUTO-GENERATED by scripts/localize-images.mjs. Product key -> number of local
// copies in public/products/gallery/<key>/ (see the script for the file order).
export const localImageCounts = ${JSON.stringify(sorted, null, 1)};
`);
console.log(`images: ${total}, downloaded: ${done}, already present: ${skipped}, failed: ${failed.length}`);
if (failed.length) console.log(failed.join('\n'));
