/**
 * Writes src/data/catalog.slim.generated.js: the product list the app ships.
 *
 * src/data/catalogSource.js does the joining and filtering (storefront
 * snapshot + 2025 catalogue ranges + local image copies). Doing it here, once,
 * instead of in every visitor's browser drops the 223 storefront records that
 * are not in the 2025 catalogue, the long Shopify links that were only ever
 * swapped for local copies, and fields nothing reads.
 *
 * Runs before `vite build` (package.json). Run it by hand after changing any
 * of the generated source files or products.js renames:
 *   node scripts/build-catalog.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { catalog, zoneMeta, rangeMeta, SLUG_RENAMES } = await import(
  pathToFileURL(path.join(root, 'src/data/catalogSource.js')).href
);
// Spelling and grammar corrections to the supplier's copy (src/data/textFixes.js).
const { fixProduct, fixDetails } = await import(pathToFileURL(path.join(root, 'src/data/textFixes.js')).href);

/**
 * Repeated photos per product, from scripts/find-duplicate-photos.mjs:
 * { key: { repeatPath: keptPath } }. The repeat leaves `imgs`, and a colour
 * variant that pointed at it points at the kept copy.
 */
const repeats = JSON.parse(fs.readFileSync(path.join(root, 'src/data/duplicatePhotos.generated.json'), 'utf8'));
let removedPhotos = 0;
const dedupe = (p) => {
  // A merged product's photos are its sources' (catalogSource.js), so are their repeats.
  const map = p.photosFrom ? Object.assign({}, ...p.photosFrom.map((k) => repeats[k])) : repeats[p.key];
  if (!map) return p;
  const imgs = (p.imgs || []).filter((u) => !map[u]);
  removedPhotos += (p.imgs || []).length - imgs.length;
  const variants = p.variants && p.variants.map((v) => (v.img && map[v.img] ? { ...v, img: map[v.img] } : v));
  return { ...p, imgs, variants };
};

/** Fields no component reads. `inCatalogue` is true for everything kept.
 *  `detailsFrom` and `keyFeatures` (merged products) go into the detail file;
 *  `photosFrom` is only for dedupe. */
const DROP = new Set(['vendor', 'hasVariants', 'rangeSource', 'inCatalogue', 'detailsFrom', 'keyFeatures', 'photosFrom']);

const slimVariant = (v) => Object.fromEntries(
  Object.entries(v).filter(([, val]) => val !== '' && val !== 0 && val !== null && val !== undefined),
);

const slimProduct = (p) => {
  const out = {};
  for (const [k, v] of Object.entries(p)) {
    if (DROP.has(k) || v === null || v === undefined) continue;
    if (Array.isArray(v) && v.length === 0 && k !== 'catalogueStandards' && k !== 'catalogueSymbols') continue;
    out[k] = k === 'variants' && Array.isArray(v) ? v.map(slimVariant) : v;
  }
  return out;
};

const slim = Object.fromEntries(Object.entries(catalog).map(([zone, list]) => [zone, list.map((p) => slimProduct(fixProduct(dedupe(p))))]));
const count = Object.values(slim).reduce((n, l) => n + l.length, 0);

const out = `// AUTO-GENERATED by scripts/build-catalog.mjs from src/data/catalogSource.js.
// Do not edit by hand; edit the sources and re-run the script.
export const zoneMeta = ${JSON.stringify(zoneMeta)};
export const rangeMeta = ${JSON.stringify(rangeMeta)};
export const SLUG_RENAMES = ${JSON.stringify(SLUG_RENAMES)};
export const catalog = ${JSON.stringify(slim)};
`;
fs.writeFileSync(path.join(root, 'src/data/catalog.slim.generated.js'), out);

/*
 * Per-product detail files: public/data/details/<key>.json with the key
 * features, design, remarks and tests, plus the diagram and design-banner
 * image. The product page used to import all of them at once (1.25 MB of
 * JavaScript for one product's ~3 KB); it now fetches its own file.
 * Generated on every build and gitignored. detailFile() in src/lib/details.js
 * must name files the same way.
 */
const load = (p) => import(pathToFileURL(path.join(root, p)).href);
const [{ productDetails }, { diagramImages }, { calloutBanners }] = await Promise.all([
  load('src/data/productDetails.js'), load('src/data/diagramImages.js'), load('src/data/calloutBanners.js'),
]);
const detailDir = path.join(root, 'public/data/details');
fs.rmSync(detailDir, { recursive: true, force: true });
fs.mkdirSync(detailDir, { recursive: true });
let detailFiles = 0;
for (const p of Object.values(catalog).flat()) {
  // A merged product (extraProducts.js MERGED) uses its first source's data.
  const from = p.detailsFrom || p.key;
  const d = productDetails[from] || {};
  const rec = fixDetails({
    keyFeatures: p.keyFeatures || d.keyFeatures, design: d.design, remarks: d.remarks, tests: d.tests,
    diagram: diagramImages[from], banner: calloutBanners[from],
  });
  if (!Object.values(rec).some((v) => v && (!Array.isArray(v) || v.length))) continue;
  fs.writeFileSync(path.join(detailDir, p.key.replace(/[^a-z0-9_-]/gi, '_') + '.json'), JSON.stringify(rec));
  detailFiles++;
}
console.log(`build-catalog: ${detailFiles} product detail files`);
console.log(`build-catalog: ${count} products, ${removedPhotos} repeated photos dropped, ${(out.length / 1024).toFixed(0)} KB`);
